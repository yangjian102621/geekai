export function getVideoProviders() {
  return Object.keys(VideoParams)
}

export function getProviderName(provider) {
  const names = {
    veo: 'Veo',
    sora: 'Sora',
    doubao: '豆包',
    keling: '可灵',
    minimax: 'MiniMax',
    wan: '通义万相',
  }
  return names[provider] || provider
}

// 获取指定 provider 的所有模型
export function getVideoModels(provider) {
  return VideoParams[provider] || []
}

// 根据 key 获取模型配置
export function getVideoModelByKey(key) {
  for (const provider in VideoParams) {
    const models = VideoParams[provider]
    const model = models.find((m) => m.key === key)
    if (model) {
      return model
    }
  }
  return null
}
